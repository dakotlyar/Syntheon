"""gpu-shaders: the GPU test's shader toolchain (Phase 4a design §13.1, D9).

Every shader is one HLSL source in src/tests/gpu/worker/shaders/ (with
common.hlsli). This script makes the outputs that are committed next to them,
in generated/:

  <name>_<vs|ps>.spv.inc   SPIR-V (DXC -spirv, Vulkan 1.3), as
                           static const std::uint32_t k<Name><Vs|Ps>Spv[]
  <name>_<vs|ps>.glsl.inc  GLSL 330 core (SPIRV-Cross), as
                           static const char k<Name><Vs|Ps>Glsl[]
  bindings.inc             every GLSL uniform block and sampler, with its
                           binding point or texture unit (GLSL 330 has no
                           binding=), as kGlBindings[]
  STAMP                    SHA-256 over the sources and versions.json

DXIL and DXBC are compiled by the Windows build itself (shaders/CMakeLists.txt).

Usage:
  build.py                   regenerate everything
  build.py --only NAME       regenerate one shader (and bindings.inc); STAMP is
                             NOT written (only a full run can vouch for every shader)
  build.py --check [--sources DIR] [--expect-stale]
                             exit 0 when STAMP matches the sources, else 1
                             ("shaders out of date: run tools/gpu-shaders/build.py");
                             with --expect-stale the other way round (the
                             planted negative). Needs no shader tools.

The tools are pinned in versions.json: DXC's Linux x64 release tarball and
SPIRV-Cross's source tag, each checked against its SHA-256, downloaded into
~/.cache/synbench/tools/ (SPIRV-Cross is built there with CMake). Linux x64
only; nothing from them ships.

STAMP = lowercase hex SHA-256 over, for each .hlsl/.hlsli sorted by path: the
path relative to the shader folder, "\\n", the file's bytes with CRLF -> LF,
"\\n"; then "versions.json", "\\n", its bytes the same way, "\\n"; then
"build.py", "\\n", this script's bytes the same way, "\\n".
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOOLS_DIR = Path(__file__).resolve().parent
VERSIONS = TOOLS_DIR / "versions.json"
SHADERS = ROOT / "src" / "tests" / "gpu" / "worker" / "shaders"
CACHE = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "synbench" / "tools"
STAGES = (("vs", "VSMain", "vs_6_0"), ("ps", "PSMain", "ps_6_0"))
STALE = "shaders out of date: run tools/gpu-shaders/build.py"
SPIRV_CROSS_URL = "https://github.com/KhronosGroup/SPIRV-Cross/archive/refs/tags/{tag}.tar.gz"

# The binding table of common.hlsli: Vulkan (set, binding) -> GL point/unit.
UBO_POINTS = {(0, 0): 0, (1, 0): 1, (0, 1): 2}
TEXTURE_UNITS = {(2, 0): 0, (2, 1): 1, (2, 2): 2, (2, 3): 3, (0, 2): 4, (0, 3): 5}

HEADER = ("// SPDX-License-Identifier: GPL-3.0-or-later\n"
          "// GENERATED by tools/gpu-shaders/build.py from {source}; do not edit.\n"
          "// {tools}\n")
GLSL_CHUNK = 12000  # MSVC limits one string literal piece to 16380 bytes (C2026)


def fail(msg, code=2):
    print(f"gpu-shaders: {msg}", file=sys.stderr)
    sys.exit(code)


def normalised(path):
    return path.read_bytes().replace(b"\r\n", b"\n")


def stamp(sources, versions):
    h = hashlib.sha256()
    files = sorted(p.relative_to(sources).as_posix() for p in sources.rglob("*")
                   if p.is_file() and p.suffix in (".hlsl", ".hlsli") and "generated" not in p.relative_to(sources).parts)
    for rel in files:
        h.update(rel.encode() + b"\n" + normalised(sources / rel) + b"\n")
    h.update(b"versions.json\n" + normalised(versions) + b"\n")
    # The generator itself: a change to how the outputs are made makes them stale.
    h.update(b"build.py\n" + normalised(Path(__file__).resolve()) + b"\n")
    return h.hexdigest()


def check(sources, expect_stale):
    stamp_file = sources / "generated" / "STAMP"
    want = stamp_file.read_text().strip() if stamp_file.exists() else ""
    fresh = want == stamp(sources, VERSIONS)
    if expect_stale:
        if fresh:
            print(f"gpu-shaders: expected stale sources in {sources}, but STAMP matches", file=sys.stderr)
            return 1
        print(f"ok  {sources} is out of date against its STAMP, as expected")
        return 0
    if not fresh:
        print(STALE, file=sys.stderr)
        return 1
    print(f"ok  {stamp_file} matches the sources")
    return 0


# --- the tools -------------------------------------------------------------

def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def fetch(url, sha256, dest):
    if dest.exists() and sha256_of(dest) == sha256:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")
    print(f"gpu-shaders: downloading {url}")
    with urllib.request.urlopen(url, timeout=120) as r, open(part, "wb") as f:
        shutil.copyfileobj(r, f)
    got = sha256_of(part)
    if got != sha256:
        part.unlink()
        fail(f"{url}: SHA-256 {got}, versions.json pins {sha256}")
    part.replace(dest)
    return dest


def extract(archive, into):
    """Unpack a verified tarball into a fresh folder of its own."""
    if into.exists():
        shutil.rmtree(into)
    into.mkdir(parents=True)
    with tarfile.open(archive) as t:
        t.extractall(into, filter="data")


def tool_dxc(v):
    d = v["dxc"]
    home = CACHE / f"dxc-{d['tag']}"
    exe = home / "bin" / "dxc"
    if not exe.exists():
        archive = fetch(d["url"], d["sha256"], CACHE / "dl" / Path(d["url"]).name)
        extract(archive, home)
    return exe


def tool_spirv_cross(v):
    s = v["spirv_cross"]
    home = CACHE / f"spirv-cross-{s['tag']}"
    exe = home / "bin" / "spirv-cross"
    if exe.exists():
        return exe
    url = SPIRV_CROSS_URL.format(tag=s["tag"])
    archive = fetch(url, s["sha256"], CACHE / "dl" / f"SPIRV-Cross-{s['tag']}.tar.gz")
    src = home / "src"
    extract(archive, src)
    (top,) = [p for p in src.iterdir() if p.is_dir()]
    build = home / "build"
    jobs = str(min(4, os.cpu_count() or 1))
    run(["cmake", "-S", str(top), "-B", str(build), "-DCMAKE_BUILD_TYPE=Release", "-DSPIRV_CROSS_CLI=ON",
         "-DSPIRV_CROSS_ENABLE_TESTS=OFF", "-DSPIRV_CROSS_SHARED=OFF", f"-DCMAKE_INSTALL_PREFIX={home}"])
    run(["cmake", "--build", str(build), "--target", "spirv-cross", "-j", jobs])
    exe.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(build / "spirv-cross", exe)
    return exe


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        fail(f"{' '.join(map(str, cmd))} failed ({r.returncode}):\n{r.stdout}{r.stderr}")
    return r.stdout


# --- one shader --------------------------------------------------------------

def camel(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def spv_inc(words, ident, source, tools):
    lines = [HEADER.format(source=source, tools=tools),
             f"static const std::uint32_t {ident}[] = {{\n"]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",\n")
    lines.append("};\n")
    return "".join(lines)


def glsl_inc(glsl, ident, source, tools):
    if ")GLSL\"" in glsl:
        fail(f"{source}: the GLSL contains the raw-string delimiter")
    # Split at line ends into pieces under MSVC's literal limit; adjacent
    # raw strings concatenate into one array.
    pieces, cur = [], ""
    for line in glsl.splitlines(keepends=True):
        if cur and len(cur) + len(line) > GLSL_CHUNK:
            pieces.append(cur)
            cur = ""
        cur += line
    pieces.append(cur)
    body = "\n".join(f'R"GLSL({p})GLSL"' for p in pieces)
    return HEADER.format(source=source, tools=tools) + f"static const char {ident}[] =\n{body};\n"


def interface_renames(reflection, direction):
    """GLSL 330 links stages by name: give every varying a name from its location."""
    args = []
    for var in reflection.get("outputs" if direction == "out" else "inputs", []):
        if "location" in var:
            args += ["--rename-interface-variable", direction, str(var["location"]), f"sb_v{var['location']}"]
    return args


def build_shader(name, dxc, spirv_cross, sources, out_dir, tools):
    source = sources / f"{name}.hlsl"
    bindings = []
    outputs = {}
    with tempfile.TemporaryDirectory(prefix="sb-shaders-") as tmp:
        tmp = Path(tmp)
        for stage, entry, profile in STAGES:
            spv = tmp / f"{name}_{stage}.spv"
            run([str(dxc), "-spirv", "-fspv-target-env=vulkan1.3", "-T", profile, "-E", entry,
                 "-Fo", str(spv), str(source)],
                env={**os.environ, "LD_LIBRARY_PATH": str(dxc.parent.parent / "lib")})
            data = spv.read_bytes()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            reflection = json.loads(run([str(spirv_cross), str(spv), "--reflect"]))
            renames = interface_renames(reflection, "out" if stage == "vs" else "in")
            glsl = run([str(spirv_cross), str(spv), "--version", "330", "--no-es", "--no-420pack-extension",
                        "--no-support-nonzero-baseinstance", "--fixup-clipspace", *renames])
            ident = f"k{camel(name)}{stage.capitalize()}"
            rel = f"src/tests/gpu/worker/shaders/{name}.hlsl ({entry})"
            outputs[f"{name}_{stage}.spv.inc"] = spv_inc(words, ident + "Spv", rel, tools)
            outputs[f"{name}_{stage}.glsl.inc"] = glsl_inc(glsl, ident + "Glsl", rel, tools)
            bindings += gl_bindings(name, reflection, glsl)
    for fname, text in outputs.items():
        write_if_changed(out_dir / fname, text)
    return bindings


def gl_bindings(name, reflection, glsl):
    found = []
    for ubo in reflection.get("ubos", []):
        key = (ubo.get("set", 0), ubo.get("binding", 0))
        if key not in UBO_POINTS:
            fail(f"{name}: uniform block {ubo['name']} at set {key[0]} binding {key[1]} isn't in the binding table")
        # SPIRV-Cross names the GLSL block after the block's type, '.' -> '_'.
        block = ubo["name"].replace(".", "_")
        if not re.search(rf"\buniform\s+{re.escape(block)}\b", glsl):
            fail(f"{name}: uniform block {block} not found in the GLSL")
        found.append((name, block, UBO_POINTS[key], True))
    images = {}
    for img in reflection.get("separate_images", []) + reflection.get("textures", []):
        key = (img.get("set", 0), img.get("binding", 0))
        if key not in TEXTURE_UNITS:
            fail(f"{name}: texture {img['name']} at set {key[0]} binding {key[1]} isn't in the binding table")
        images[img["name"]] = TEXTURE_UNITS[key]
    for sampler in re.findall(r"\buniform\s+\w*sampler\w*\s+(\w+)\s*;", glsl):
        if sampler in images:
            found.append((name, sampler, images[sampler], False))
            continue
        combined = sampler.removeprefix("SPIRV_Cross_Combined")
        owners = [img for img in images if combined.startswith(img)]
        if combined == sampler or not owners:
            fail(f"{name}: can't tell which texture the GLSL sampler {sampler} samples")
        found.append((name, sampler, images[max(owners, key=len)], False))
    return found


def bindings_inc(entries, tools):
    lines = [HEADER.format(source="every shader's reflection", tools=tools),
             "// GLSL 330 has no binding=: the GL backend binds these after linking\n",
             "// (glUniformBlockBinding for a block, glUniform1i for a sampler).\n",
             "struct GlBinding { const char *shader; const char *glslName; int unit; bool block; };\n",
             "static const GlBinding kGlBindings[] = {\n"]
    for shader, glsl_name, unit, block in sorted(set(entries)):
        lines.append(f'    {{"{shader}", "{glsl_name}", {unit}, {"true" if block else "false"}}},\n')
    lines.append("};\n")
    return "".join(lines)


def write_if_changed(path, text):
    data = text.encode()
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def generate(only):
    versions = json.loads(VERSIONS.read_text())
    dxc = tool_dxc(versions)
    spirv_cross = tool_spirv_cross(versions)
    tools = f"DXC {versions['dxc']['tag']}, SPIRV-Cross {versions['spirv_cross']['tag']}"
    out_dir = SHADERS / "generated"
    out_dir.mkdir(exist_ok=True)
    names = sorted(p.stem for p in SHADERS.glob("*.hlsl"))
    if only and only not in names:
        fail(f"no shader {only}.hlsl in {SHADERS}")
    # bindings.inc covers every shader, so it is always rebuilt from all of
    # them; --only skips writing the other shaders' .inc files.
    entries = []
    with tempfile.TemporaryDirectory(prefix="sb-shaders-out-") as scratch:
        for name in names:
            target = out_dir if (not only or name == only) else Path(scratch)
            entries += build_shader(name, dxc, spirv_cross, SHADERS, target, tools)
    write_if_changed(out_dir / "bindings.inc", bindings_inc(entries, tools))
    if only:
        # The other shaders' outputs weren't rewritten, so the STAMP can't vouch for them.
        print(f"ok  {only} -> {out_dir.relative_to(ROOT)}; STAMP not written: run build.py without --only")
        return 0
    write_if_changed(out_dir / "STAMP", stamp(SHADERS, VERSIONS) + "\n")
    print(f"ok  {len(names)} shader(s) -> {out_dir.relative_to(ROOT)}")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--expect-stale", action="store_true")
    ap.add_argument("--sources", type=Path, default=SHADERS)
    ap.add_argument("--only")
    args = ap.parse_args()
    if args.check:
        return check(args.sources.resolve(), args.expect_stale)
    if args.expect_stale or args.sources != SHADERS:
        fail("--expect-stale and --sources go with --check")
    return generate(args.only)


if __name__ == "__main__":
    sys.exit(main())
