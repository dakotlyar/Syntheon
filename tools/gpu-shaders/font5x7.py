"""font5x7: the overlay's bitmap font (Phase 4a design §5.9, task 8a).

Reads 5x7.bdf from X.Org's font-misc-misc release tarball (the URL and SHA-256
are pinned under "font_misc_misc" in versions.json; downloaded into
~/.cache/synbench/tools/ and checked) and writes
src/tests/gpu/worker/scene/bitmap_font.inc: for ASCII 32..126 (95 glyphs) 7
rows of 5 bits, bit 4 = the leftmost pixel, row 0 = the top. The font is
public domain ("Public domain font.  Share and enjoy.").

Usage: font5x7.py [--check]    --check exits 1 if the committed file differs.
Running it twice gives the same file.
"""
import argparse
import hashlib
import io
import json
import os
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSIONS = Path(__file__).resolve().parent / "versions.json"
OUT = ROOT / "src" / "tests" / "gpu" / "worker" / "scene" / "bitmap_font.inc"
CACHE = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "synbench" / "tools"
FIRST, COUNT, ROWS, COLS = 32, 95, 7, 5


def fail(msg):
    print(f"font5x7: {msg}", file=sys.stderr)
    sys.exit(2)


def fetch(url, sha256):
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / url.rsplit("/", 1)[1]
    if not path.exists():
        # To a .part file, renamed only once its SHA-256 matches: an interrupted
        # download never leaves a file that looks complete.
        part = path.with_name(path.name + ".part")
        with urllib.request.urlopen(url, timeout=60) as r:
            part.write_bytes(r.read())
        got = hashlib.sha256(part.read_bytes()).hexdigest()
        if got != sha256:
            part.unlink()
            fail(f"{url}: SHA-256 {got}, versions.json pins {sha256}")
        os.replace(part, path)
    got = hashlib.sha256(path.read_bytes()).hexdigest()
    if got != sha256:
        fail(f"{path}: SHA-256 {got}, versions.json pins {sha256}")
    return path


def read_bdf(tar_path):
    with tarfile.open(tar_path) as tar:
        for member in tar.getmembers():
            if member.isfile() and member.name.endswith("/5x7.bdf"):
                return tar.extractfile(member).read().decode("ascii")
    fail("5x7.bdf is not in the tarball")


def glyphs(bdf):
    """encoding -> 7 row values of 5 bits (bit 4 = the leftmost pixel)."""
    # The font box is 5 x 7 with its lower-left corner at (0, -1): row r (0 = top) is y = 5 - r.
    out = {}
    lines = io.StringIO(bdf).read().splitlines()
    i = 0
    while i < len(lines):
        if not lines[i].startswith("STARTCHAR"):
            i += 1
            continue
        enc, bbx, bitmap = None, None, []
        while not lines[i].startswith("ENDCHAR"):
            parts = lines[i].split()
            if parts[0] == "ENCODING":
                enc = int(parts[1])
            elif parts[0] == "BBX":
                bbx = tuple(int(x) for x in parts[1:5])
            elif parts[0] == "BITMAP":
                i += 1
                while not lines[i].startswith("ENDCHAR"):
                    bitmap.append(int(lines[i], 16))
                    i += 1
                break
            i += 1
        if enc is not None and FIRST <= enc < FIRST + COUNT:
            w, h, xoff, yoff = bbx
            rows = [0] * ROWS
            for j, byte in enumerate(bitmap):  # j = 0 is the top row of the glyph
                r = 5 - (yoff + h - 1 - j)
                if not 0 <= r < ROWS:
                    fail(f"glyph {enc}: row {j} falls outside the 5x7 box")
                rows[r] = bitmap_to_cols(byte, w, xoff)
            out[enc] = rows
        i += 1
    for enc in range(FIRST, FIRST + COUNT):
        if enc not in out:
            fail(f"glyph {enc} is missing")
    return out


def bitmap_to_cols(byte, w, xoff):
    """The glyph row `byte` (bit 7 = its leftmost pixel, w pixels wide) placed in the 5-column box."""
    bits = 0
    for c in range(w):
        if byte & (0x80 >> c):
            col = xoff + c
            if not 0 <= col < COLS:
                fail("a glyph pixel falls outside the 5x7 box")
            bits |= 1 << (COLS - 1 - col)
    return bits


def render(table, url):
    lines = ["// SPDX-License-Identifier: GPL-3.0-or-later",
             "// GENERATED by tools/gpu-shaders/font5x7.py; do not edit.",
             "// Source: the 5x7 font of X.Org's font-misc-misc (misc-fixed), "
             f"{url.rsplit('/', 1)[1]}.",
             '// Public domain: "Public domain font.  Share and enjoy."',
             "// 95 glyphs (ASCII 32..126), 7 rows of 5 bits, bit 4 = the leftmost pixel, row 0 = the top."]
    for enc in range(FIRST, FIRST + COUNT):
        rows = ", ".join(f"0x{r:02X}" for r in table[enc])
        label = chr(enc).replace("\\", "backslash")
        lines.append(f"{{{rows}}},  // {label}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    v = json.loads(VERSIONS.read_text())["font_misc_misc"]
    text = render(glyphs(read_bdf(fetch(v["url"], v["sha256"]))), v["url"])
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("bitmap_font.inc out of date: run tools/gpu-shaders/font5x7.py", file=sys.stderr)
            return 1
        print(f"ok  {OUT} matches the font")
        return 0
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
        print(f"wrote {OUT}")
    else:
        print(f"unchanged {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
