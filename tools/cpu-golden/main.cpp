// synbench-cpu-golden (Phase 2 design §6.4): writes the CPU test's golden
// tables, src/tests/cpu/golden/*.inc, from the reference implementations.
//
//   synbench-cpu-golden <dir>           write every table into <dir>
//   synbench-cpu-golden --check <dir>   compare with the tables in <dir>;
//                                       exit 1 and name each one that differs
//
// Run by hand (Kanan) when a kernel's definition changes, then commit the
// tables with a CPU testVersion bump. CI runs --check on every platform.
#include "tests/cpu/compress/corpus.h"

#include <cstdio>
#include <filesystem>
#include <fstream>
#include <functional>
#include <iterator>
#include <sstream>
#include <string>
#include <thread>
#include <vector>

namespace {

struct Table {
    const char *file;
    std::function<std::string()> make;  // the file's content
};

std::string header(const char *what, const char *how)
{
    std::ostringstream s;
    s << "// SPDX-License-Identifier: GPL-3.0-or-later\n"
      << "// GENERATED by tools/cpu-golden (synbench-cpu-golden); do not edit. A change\n"
      << "// here changes what the CPU test accepts: bump its testVersion.\n"
      << "// " << what << "\n"
      << "// " << how << "\n";
    return s.str();
}

std::string hex32(std::uint32_t v)
{
    char buf[16];
    std::snprintf(buf, sizeof buf, "0x%08Xu", v);
    return buf;
}

std::string corpusTable()
{
    const unsigned threads = std::max(1u, std::thread::hardware_concurrency());
    const std::vector<std::uint8_t> corpus = sb::cpu::generateCorpus(int(threads));
    return header("The compression corpus (section 5.4): 32 MiB, 128 blocks of 256 KiB.",
                  "kCorpusCrc32 = zlib crc32() of sb::cpu::generateCorpus().")
           + "inline constexpr std::uint32_t kCorpusCrc32 = " + hex32(sb::cpu::crc32Of(corpus)) + ";\n";
}

const std::vector<Table> &tables()
{
    static const std::vector<Table> t = {
        {"corpus.inc", corpusTable},
    };
    return t;
}

std::string readFile(const std::filesystem::path &p)
{
    std::ifstream in(p, std::ios::binary);
    return std::string(std::istreambuf_iterator<char>(in), {});
}

} // namespace

int main(int argc, char **argv)
{
    const bool check = argc == 3 && std::string(argv[1]) == "--check";
    if (!(argc == 2 || check)) {
        std::fprintf(stderr, "usage: synbench-cpu-golden [--check] <golden dir>\n");
        return 2;
    }
    const std::filesystem::path dir = argv[argc - 1];
    int differ = 0;
    for (const Table &t : tables()) {
        const std::string content = t.make();
        const std::filesystem::path file = dir / t.file;
        if (check) {
            if (readFile(file) != content) {
                std::printf("DIFFERS  %s\n--- regenerated:\n%s", file.string().c_str(), content.c_str());
                ++differ;
            } else {
                std::printf("ok       %s\n", file.string().c_str());
            }
        } else {
            std::ofstream out(file, std::ios::binary);
            out << content;
            std::printf("wrote    %s\n", file.string().c_str());
        }
    }
    return differ ? 1 : 0;
}
